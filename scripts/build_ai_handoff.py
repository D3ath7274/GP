"""Build/check the AI file reference and source fingerprints without importing runtime code."""
import argparse
import ast
import hashlib
import json
from pathlib import Path
import subprocess
from check_docs_sync import is_implementation

ROOT = Path(__file__).resolve().parents[1]
PURPOSES = "docs-site/reference/file-purposes.json"
MANIFEST = "docs-site/reference/codebase-snapshot.json"
REFERENCE = "PROJECT_AI_HANDBOOK.md"
CONTEXT = "CODEBASE_AI_HANDOFF.md"
BINARY_SUFFIXES = {".joblib", ".h5", ".keras", ".pkl", ".onnx", ".pt"}

def tracked():
    return sorted(p.decode("utf-8") for p in subprocess.check_output(
        ["git", "ls-files", "-z"], cwd=ROOT).split(b"\0") if p)

def read(name, staged=False):
    if staged:
        return subprocess.check_output(["git", "show", ":" + name], cwd=ROOT)
    return (ROOT / name).read_bytes()

def symbols(source):
    tree = ast.parse(source)
    output = []
    class Visitor(ast.NodeVisitor):
        def __init__(self):
            self.stack = []
        def record(self, node, kind):
            output.append({"name": ".".join(self.stack + [node.name]), "kind": kind,
                           "line": node.lineno, "end_line": node.end_lineno})
            self.stack.append(node.name)
            self.generic_visit(node)
            self.stack.pop()
        def visit_ClassDef(self, node):
            self.record(node, "class")
        def visit_FunctionDef(self, node):
            self.record(node, "function")
        def visit_AsyncFunctionDef(self, node):
            self.record(node, "async function")
    Visitor().visit(tree)
    imports = sorted({n.module or "" for n in ast.walk(tree) if isinstance(n, ast.ImportFrom)} |
                     {a.name for n in ast.walk(tree) if isinstance(n, ast.Import) for a in n.names})
    return output, imports

def build(files, catalog, reader, base, context=""):
    if set(catalog) != {"version", "files", "local_only"} or catalog["version"] != "file-purposes-v1":
        raise ValueError("Invalid file-purpose catalog")
    if set(files) != set(catalog["files"]):
        raise ValueError("Update file purposes; missing=" + repr(sorted(set(files)-set(catalog["files"]))) +
                         "; obsolete=" + repr(sorted(set(catalog["files"])-set(files))))
    records = []
    for name in files:
        purpose = catalog["files"][name]
        if not isinstance(purpose, str) or len(purpose.split()) < 6:
            raise ValueError("Substantive purpose required: " + name)
        item = {"path": name, "purpose": purpose}
        suffix = Path(name).suffix
        if is_implementation(name) or (suffix == ".json" and name != MANIFEST) or name.startswith("examples/") or name.startswith("tests/fixtures/") or name.startswith("Controller/ml_models/"):
            raw = reader(name)
            if suffix not in BINARY_SUFFIXES:
                raw = raw.replace(b"\r\n", b"\n")
            item["sha256"] = hashlib.sha256(raw).hexdigest()
            item["canonical_bytes"] = len(raw)
        if suffix == ".py":
            item["symbols"], item["imports"] = symbols(reader(name).decode("utf-8-sig"))
        records.append(item)
    snapshot = {"version": "ai-codebase-snapshot-v1", "reference_base_commit": base,
                "scope": "Tracked paths; code/contracts/fixtures use LF-normalized hashes; joblib/H5 artifacts use raw hashes. canonical_bytes is the hashed length. Documentation narratives need review. Untracked/private/generated dependencies are excluded.",
                "context_sha256": hashlib.sha256(context.encode("utf-8")).hexdigest(),
                "files": records, "local_only": catalog["local_only"]}
    lines = ["# Adaptive IPS framework — complete AI handbook", "",
             context.strip(), "", "---", "",
             "# Complete tracked-file and symbol reference", "",
             "Generated by scripts/build_ai_handoff.py from the authored file-purpose catalog and AST source index.",
             "Read CODEBASE_AI_HANDOFF.md first. This index covers every tracked path, not every installed dependency/cache file.",
             "Reference base: " + base + ". Source fingerprints, rather than this base alone, identify the described implementation.",
             "Do not treat file presence, a function name, comments or AST extraction as proof of runtime success.", "",
             "## Every tracked file", "", "| Path | Role and relationship |", "| --- | --- |"]
    for record in records:
        lines.append("| " + record["path"] + " | " + record["purpose"].replace("|", "/").replace("\n", " ") + " |")
    lines += ["", "## Python symbols and direct imports", "",
              "Line numbers identify this snapshot; verify fingerprints before using them. Conditional definitions and nested helpers are included.",
              "Imports list direct source imports, including standard/optional dependencies; they do not assert that every branch runs.", ""]
    for record in records:
        if "symbols" not in record:
            continue
        lines += ["### " + record["path"], "", record["purpose"], "",
                  "Direct imports: " + ", ".join(record["imports"]) + ".", "",
                  "| Symbol | Kind | Source lines |", "| --- | --- | --- |"]
        for symbol in record["symbols"]:
            lines.append("| " + symbol["name"] + " | " + symbol["kind"] + " | " +
                         str(symbol["line"]) + "–" + str(symbol["end_line"]) + " |")
        lines.append("")
    lines += ["## Local-only and excluded material", ""]
    for name, purpose in catalog["local_only"].items():
        lines += ["- **" + name + "**: " + purpose]
    lines += ["", "No dataset rows, agent-local permissions, credentials or binary model contents are embedded here.",
              "Binary artifacts are fingerprinted, not executed/unpickled by the builder.",
              "To refresh after edits, update file-purposes.json for new/deleted files, stage new paths, run the builder with --write, review, then stage the generated files.",
              "The checker can detect hash/path/index drift; it cannot prove that authored prose correctly explains changed semantics.", ""]
    return snapshot, "\n".join(lines)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--staged", action="store_true")
    args = parser.parse_args()
    if args.write and args.staged:
        parser.error("--write uses reviewed working-tree source; --staged is check-only")
    try:
        files = tracked()
        catalog = json.loads(read(PURPOSES, args.staged))
        old = json.loads(read(MANIFEST, args.staged)) if not args.write else None
        base = old["reference_base_commit"] if old else subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
        context = read(CONTEXT,args.staged).decode("utf-8").replace("\r\n", "\n")
        for markdown, page in ((CONTEXT,"docs-site/developers/ai-handoff.mdx"),
                               ("DEVELOPER_STUDY_ROADMAP.md","docs-site/developers/study-roadmap.mdx")):
            authored=read(markdown,args.staged).decode("utf-8").replace("\r\n", "\n").split("\n\n",1)[1].strip()
            website=read(page,args.staged).decode("utf-8").replace("\r\n", "\n").split("---\n",2)[2].strip()
            if authored != website:
                raise ValueError("Standalone/site bodies differ: " + markdown)
        snapshot, reference = build(files, catalog, lambda p:read(p,args.staged), base, context)
        encoded = json.dumps(snapshot, indent=2, ensure_ascii=False) + "\n"
        if args.write:
            (ROOT/MANIFEST).write_text(encoded, encoding="utf-8")
            (ROOT/REFERENCE).write_text(reference, encoding="utf-8")
        elif json.loads(read(MANIFEST,args.staged)) != snapshot or read(REFERENCE,args.staged).decode("utf-8").replace("\r\n", "\n") != reference:
            raise ValueError("Handoff inventory is stale; review source/prose and run python scripts/build_ai_handoff.py --write")
        print(json.dumps({"valid":True,"tracked_files":len(files),"fingerprinted":sum("sha256" in r for r in snapshot["files"]),
                          "meaning":"Coverage/fingerprint/AST freshness, not semantic or production qualification"}))
    except (OSError, ValueError, KeyError, SyntaxError, subprocess.CalledProcessError) as error:
        parser.exit(1, str(error)+"\n")

if __name__ == "__main__":
    main()
